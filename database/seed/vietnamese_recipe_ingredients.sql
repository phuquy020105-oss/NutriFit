-- Existing recipes must ALREADY have the complete exact ingredient set.
-- Missing, extra, duplicate or changed rows abort; never repair someone else's recipe silently.
INSERT INTO _nf_assert (check_name, ok)
SELECT 'existing_recipe_ingredients_exact', IF((NOT EXISTS (
 SELECT s.recipe_ref, s.food_ref FROM _nf_ingredient_stage s
 JOIN _nf_recipe_map r ON r.ref = s.recipe_ref AND r.was_existing = TRUE
 JOIN _nf_food_map f ON f.ref = s.food_ref
 LEFT JOIN recipeingredients i ON i.recipe_id = r.recipe_id AND i.food_id = f.food_id
 AND i.quantity_grams = s.quantity_grams
 GROUP BY s.recipe_ref, s.food_ref HAVING COUNT(i.ingredient_id) <> 1)), 1, NULL);

INSERT INTO _nf_assert (check_name, ok)
SELECT 'existing_recipes_have_no_extra_rows', IF((NOT EXISTS (
 SELECT 1 FROM _nf_recipe_map r JOIN recipeingredients i ON i.recipe_id = r.recipe_id
 LEFT JOIN _nf_food_map f ON f.food_id = i.food_id
 LEFT JOIN _nf_ingredient_stage s ON s.recipe_ref = r.ref AND s.food_ref = f.ref
 AND s.quantity_grams = i.quantity_grams
 WHERE r.was_existing = TRUE AND s.recipe_ref IS NULL)), 1, NULL);

